-- ============================================================================
-- All-Time Football Stats — Schéma PostgreSQL (Supabase)
--
-- Règles métier :
--   * CLUB      : matchs officiels uniquement (championnat, coupes, Europe,
--                 super-coupes, play-offs). Amicaux de club INTERDITS.
--   * NATIONAL  : sélections "A" uniquement (tournois, éliminatoires,
--                 Ligue des Nations, amicaux FIFA officiels).
--                 Espoirs/U21, JO et sélections régionales INTERDITS.
--   * Métriques : matches, goals, assists (uniquement).
--
-- Exécution : psql "$DATABASE_URL" -f db/init.sql
--             ou éditeur SQL Supabase.
-- ============================================================================

create extension if not exists pg_trgm;

-- ----------------------------------------------------------------------------
-- 1. players
-- ----------------------------------------------------------------------------
create table if not exists players (
    id                bigint generated by default as identity primary key,
    transfermarkt_id  bigint not null unique,
    fbref_id          text unique,
    slug              text not null unique,
    name              text not null,
    first_name        text,
    last_name         text,
    birth_date        date,
    nationality       text,
    photo_url         text,
    last_season       smallint,
    is_active         boolean not null default false,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

create index if not exists idx_players_name_trgm
    on players using gin (name gin_trgm_ops);
create index if not exists idx_players_nationality
    on players (nationality);
create index if not exists idx_players_active
    on players (is_active) where is_active;

-- ----------------------------------------------------------------------------
-- 2. player_season_stats — détail par saison, équipe et type de compétition
-- ----------------------------------------------------------------------------
create table if not exists player_season_stats (
    id                bigint generated by default as identity primary key,
    player_id         bigint not null references players(id) on delete cascade,
    season            smallint not null,       -- ex. 2025 = saison 2025/2026
    team_name         text not null,
    category          text not null check (category in ('CLUB', 'NATIONAL')),
    competition_type  text not null check (competition_type in (
                          -- CLUB
                          'league', 'cup', 'european_cup', 'super_cup',
                          'playoff', 'other',
                          -- NATIONAL
                          'tournament', 'qualifier', 'nations_league', 'friendly'
                      )),
    matches           integer not null default 0 check (matches >= 0),
    goals             integer not null default 0 check (goals >= 0),
    assists           integer not null default 0 check (assists >= 0),
    source            text not null default 'transfermarkt'
                          check (source in ('transfermarkt', 'fbref')),
    updated_at        timestamptz not null default now(),
    constraint uq_player_season_slice
        unique (player_id, season, team_name, category, competition_type),
    constraint chk_category_compatibility check (
        (category = 'CLUB' and competition_type in
            ('league', 'cup', 'european_cup', 'super_cup', 'playoff', 'other'))
        or
        (category = 'NATIONAL' and competition_type in
            ('tournament', 'qualifier', 'nations_league', 'friendly'))
    )
);

create index if not exists idx_player_season_stats_season
    on player_season_stats (season);

-- ----------------------------------------------------------------------------
-- 3. player_career_totals — cache agrégé Club + Sélection (lecture seule UI)
--    Recalculé intégralement par refresh_career_totals().
-- ----------------------------------------------------------------------------
create table if not exists player_career_totals (
    player_id         bigint primary key references players(id) on delete cascade,
    club_matches      integer not null default 0,
    club_goals        integer not null default 0,
    club_assists      integer not null default 0,
    national_matches  integer not null default 0,
    national_goals    integer not null default 0,
    national_assists  integer not null default 0,
    total_matches     integer generated always as (club_matches + national_matches) stored,
    total_goals       integer generated always as (club_goals + national_goals) stored,
    total_assists     integer generated always as (club_assists + national_assists) stored,
    goal_ratio        numeric(5, 3) check (goal_ratio is null or goal_ratio >= 0),
    updated_at        timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 4. updated_at automatique
-- ----------------------------------------------------------------------------
create or replace function set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_players_updated_at on players;
create trigger trg_players_updated_at
    before update on players
    for each row execute function set_updated_at();

drop trigger if exists trg_player_season_stats_updated_at on player_season_stats;
create trigger trg_player_season_stats_updated_at
    before update on player_season_stats
    for each row execute function set_updated_at();

drop trigger if exists trg_player_career_totals_updated_at on player_career_totals;
create trigger trg_player_career_totals_updated_at
    before update on player_career_totals
    for each row execute function set_updated_at();

-- ----------------------------------------------------------------------------
-- 5. Recalcul complet du cache (appelé par les scripts d'ingestion)
--    goal_ratio = total de buts / total de matchs (but par match).
-- ----------------------------------------------------------------------------
create or replace function refresh_career_totals() returns void
language plpgsql as $$
declare
    v_rows integer;
begin
    -- purge des joueurs sans statistique restante
    delete from player_career_totals c
    where not exists (
        select 1 from player_season_stats s where s.player_id = c.player_id
    );

    with src as (
        select
            player_id,
            coalesce(sum(matches) filter (where category = 'CLUB'), 0)     as club_matches,
            coalesce(sum(goals)   filter (where category = 'CLUB'), 0)     as club_goals,
            coalesce(sum(assists) filter (where category = 'CLUB'), 0)     as club_assists,
            coalesce(sum(matches) filter (where category = 'NATIONAL'), 0) as national_matches,
            coalesce(sum(goals)   filter (where category = 'NATIONAL'), 0) as national_goals,
            coalesce(sum(assists) filter (where category = 'NATIONAL'), 0) as national_assists,
            sum(matches) as all_matches,
            sum(goals)   as all_goals
        from player_season_stats
        group by player_id
    )
    insert into player_career_totals (
        player_id, club_matches, club_goals, club_assists,
        national_matches, national_goals, national_assists,
        goal_ratio, updated_at
    )
    select
        player_id, club_matches, club_goals, club_assists,
        national_matches, national_goals, national_assists,
        case when all_matches > 0
             then round(all_goals::numeric / all_matches, 3)
        end,
        now()
    from src
    on conflict (player_id) do update set
        club_matches     = excluded.club_matches,
        club_goals       = excluded.club_goals,
        club_assists     = excluded.club_assists,
        national_matches = excluded.national_matches,
        national_goals   = excluded.national_goals,
        national_assists = excluded.national_assists,
        goal_ratio       = excluded.goal_ratio,
        updated_at       = now();

    get diagnostics v_rows = row_count;
    raise notice 'refresh_career_totals: % joueurs recalculés', v_rows;
end;
$$;

